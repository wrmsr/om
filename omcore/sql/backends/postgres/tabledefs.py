POSTGRES_INTEGER_TYPES_BY_BITS: ta.Mapping[int, str] = {
    16: 'smallint',
    32: 'integer',
    64: 'bigint',
}


class PostgresTabledefRenderer(Renderer):
    max_ident_length = 63

    def builtin_trigger_renderers(self) -> ta.Sequence[TriggerRenderer]:
        return [PostgresUpdatedAtTriggerRenderer()]

    def column_type(self, c: Column, *, is_identity: bool, indexed: bool = False) -> str:
        if isinstance(c.type, String):
            return f'varchar({c.type.length})' if c.type.length is not None else 'text'
        elif isinstance(c.type, Uuid):
            return 'uuid'
        elif isinstance(c.type, Integer):
            return POSTGRES_INTEGER_TYPES_BY_BITS[self.integer_bits(c.type, is_identity=is_identity)]
        elif isinstance(c.type, Datetime):
            return 'timestamp with time zone'
        elif isinstance(c.type, Boolean):
            return 'boolean'
        elif isinstance(c.type, Float):
            return 'double precision'
        elif isinstance(c.type, Bytes):
            return 'bytea'
        else:
            raise TypeError(c.type)

    def column_identity_sql(self, c: Column) -> str:
        return 'generated by default as identity'

    def drop_statement(self, tbl: TableDef) -> str:
        return f'drop table if exists {self.qname(tbl.name)} cascade'

    def index_statements(self, table_name: QualifiedName, e: Index, opts: Renderer.CreateOptions) -> list[str]:
        if Clustered not in e.options:
            return super().index_statements(table_name, e, opts)

        # A postgres table is a heap, which nothing keeps in any order - not even that of its primary key, so there is
        # no other shape to give it. The most there is to do is to mark the index as the one to cluster on: a `cluster`
        # then puts the table in its order, as of then, and what comes after lands wherever it fits.
        stmts = super().index_statements(
            table_name,
            dc.replace(e, options=tv.TypedValues(*(o for o in e.options if not isinstance(o, Clustered)))),
            opts,
        )
        stmts.append(f'alter table {self.qname(table_name)} cluster on {self.quote_ident(index_name(table_name, e))}')
        return stmts

    def alter_column_statements(self, op: AlterColumn) -> list[str]:
        c = op.column
        nn = 'set' if not c.nullable else 'drop'
        return [
            f'alter table {self.qname(op.table)} alter column {self.quote_ident(c.name)} type {self.column_type(c, is_identity=False)}',  # noqa
            f'alter table {self.qname(op.table)} alter column {self.quote_ident(c.name)} {nn} not null',
        ]
