CREATE_UPDATED_AT_TRIGGER_FUNCTION_SRC = """\
create or replace function {function_name}()
returns trigger
language plpgsql
as $$
begin
  if new.{column_name} is not distinct from old.{column_name} then
    new.{column_name} := current_timestamp;
  end if;

  return new;
end;
$$\
"""


CREATE_UPDATED_AT_TRIGGER_SRC = """\
create {or_replace}trigger {trigger_name}
before update on {table_name}
for each row
execute function {function_name}()
"""


class PostgresUpdatedAtTriggerRenderer(TriggerRenderer[UpdatedAtTrigger]):
    @property
    def trigger_cls(self) -> type[UpdatedAtTrigger]:
        return UpdatedAtTrigger

    @classmethod
    def function_name(cls, trigger_name: str) -> str:
        # The trigger function is a separate, schema-level object. Naming it by a fixed rewrite of the trigger's own
        # name lets a drop - which knows only the trigger name - find it again.
        return trigger_name.replace('__trigger__', '__function__', 1)

    def create_statements(
            self,
            r: Renderer,
            tbl: TableDef,
            t: UpdatedAtTrigger,
            opts: Renderer.CreateOptions,
    ) -> list[str]:
        trigger_name = t.trigger_name(tbl.name)
        function_qn = tbl.name.sibling(self.function_name(trigger_name))

        return [
            CREATE_UPDATED_AT_TRIGGER_FUNCTION_SRC.format(
                function_name=r.qname(function_qn),
                column_name=r.quote_ident(t.column),
            ),
            CREATE_UPDATED_AT_TRIGGER_SRC.format(
                # Postgres 14+ has 'create or replace trigger', which stands in for the missing 'if not exists'.
                or_replace='or replace ' if opts.if_not_exists else '',
                trigger_name=r.quote_ident(trigger_name),
                table_name=r.qname(tbl.name),
                function_name=r.qname(function_qn),
            ),
        ]

    def drop_statements(
            self,
            r: Renderer,
            table_name: QualifiedName,
            name: str,
    ) -> list[str]:
        function_qn = table_name.sibling(self.function_name(name))

        return [
            f'drop trigger if exists {r.quote_ident(name)} on {r.qname(table_name)}',
            f'drop function if exists {r.qname(function_qn)}()',
        ]


